#!/usr/bin/env python3
"""Build the generated figure tables of Appendix I from primer/figures.yaml.

Usage:
  python3 build_appendix_i.py figures.yaml TARGET.md          rewrite the block in TARGET.md
  python3 build_appendix_i.py --check figures.yaml TARGET.md  exit 1 if the block is stale

Exit codes: 0 ok; 1 --check found a difference; 2 bad input (YAML outside the
supported subset, unknown section prefix, missing or duplicated markers).
Standard library only. The YAML subset: comment and blank lines before the
first item; then items of the form
  - key: "..."
    value: "..."   (unit, model_id, source_url, verified, note follow, in that order)
All values are double-quoted strings; only \\" and \\\\ escapes are allowed.
"""
import re
import sys

START = ("<!-- figures:start (generated by build_appendix_i.py from primer/figures.yaml; "
         "edit the YAML, not this table) -->")
END = "<!-- figures:end -->"
FIELDS = ["key", "value", "unit", "model_id", "source_url", "verified", "note"]

# Section prefix (first dotted segment of key) -> heading, in output order.
SECTIONS = [
    ("class", "Model classes"),
    ("vendor", "Vendor default for model selection"),
    ("fable", "Current Fable-class model"),
    ("opus", "Current Opus-class model"),
    ("sonnet", "Current Sonnet-class model"),
    ("haiku", "Current Haiku-class model"),
    ("mythos", "Current Mythos-class model (limited availability)"),
    ("legacy", "Legacy models still available"),
    ("retire", "Lifecycle dates for legacy and deprecated models"),
    ("cache", "Prompt caching"),
    ("cacheinv", "Cache invalidation"),
    ("longctx", "Long-context pricing"),
    ("tokenizer", "Tokenizer"),
    ("batch", "Batch behavior a cost model depends on"),
    ("residency", "Data residency"),
    ("fastmode", "Fast mode"),
    ("tools", "Tools and context"),
    ("toolsearch", "Tool search"),
    ("stop", "Refusal signaling and stop reasons"),
    ("thinking", "Thinking control"),
    ("params", "Request parameters"),
    ("retrieval", "Retrieval (Contextual Retrieval post, not re-verified)"),
    ("a2a", "Agent-to-agent (A2A), not an Anthropic source, not re-verified"),
    ("entry", "Entry points and build-time interfaces, not re-verified"),
    ("routes", "Delivery routes and compliance mechanics, not re-verified"),
]
PAGES = {
    "https://platform.claude.com/docs/en/models/overview": "Models overview",
    "https://platform.claude.com/docs/en/about-claude/pricing": "Pricing",
    "https://platform.claude.com/docs/en/build-with-claude/prompt-caching": "Prompt caching",
    "https://platform.claude.com/docs/en/about-claude/model-deprecations": "Model deprecations",
    "https://platform.claude.com/docs/en/agents-and-tools/tool-use/tool-search-tool": "Tool search tool",
    "https://platform.claude.com/docs/en/build-with-claude/batch-processing": "Batch processing",
    "https://platform.claude.com/docs/en/build-with-claude/data-residency": "Data residency",
    "https://platform.claude.com/docs/en/build-with-claude/handling-stop-reasons": "Handling stop reasons",
}
QSTR = r'"((?:[^"\\]|\\["\\])*)"'
ITEM_RE = re.compile(r'^- key: ' + QSTR + r'$')
FIELD_RE = re.compile(r'^  ([a-z_]+): ' + QSTR + r'$')
KEY_RE = re.compile(r'^[a-z0-9_]+(\.[a-z0-9_*]+)+$')


class InputError(Exception):
    pass


def unq(s):
    return re.sub(r'\\(["\\])', r'\1', s)


def parse(path):
    with open(path, encoding="utf-8") as fh:
        lines = fh.read().split("\n")
    if lines and lines[-1] == "":
        lines.pop()
    items, cur, seen = [], None, set()
    for n, line in enumerate(lines, 1):
        if cur is None and not items and (line == "" or line.startswith("#")):
            continue
        m = ITEM_RE.match(line)
        if m:
            if cur is not None:
                items.append(cur)
            key = unq(m.group(1))
            if not KEY_RE.match(key):
                raise InputError("line %d: malformed key %r" % (n, key))
            if key in seen:
                raise InputError("line %d: duplicate key %r" % (n, key))
            seen.add(key)
            cur = {"key": key, "_order": ["key"]}
            continue
        m = FIELD_RE.match(line)
        if m and cur is not None:
            name = m.group(1)
            expected = FIELDS[len(cur["_order"])] if len(cur["_order"]) < len(FIELDS) else None
            if name != expected:
                raise InputError("line %d: expected field %r, found %r" % (n, expected, name))
            cur[name] = unq(m.group(2))
            cur["_order"].append(name)
            continue
        raise InputError("line %d: not understood: %r" % (n, line))
    if cur is not None:
        items.append(cur)
    if not items:
        raise InputError("no items")
    for it in items:
        if it["_order"] != FIELDS:
            raise InputError("item %r: fields must be exactly %s" % (it["key"], ", ".join(FIELDS)))
        prefix = it["key"].split(".")[0]
        if prefix not in dict(SECTIONS):
            raise InputError("item %r: unknown section prefix %r" % (it["key"], prefix))
    return items


def cell(s):
    return s.replace("|", "\\|").strip()


def render(items):
    out = [START, ""]
    for prefix, title in SECTIONS:
        rows = [it for it in items if it["key"].split(".")[0] == prefix]
        if not rows:
            continue
        out.append("#### " + title)
        out.append("")
        out.append("| Key | Value | Model ID | Verified | Source | Note |")
        out.append("| --- | --- | --- | --- | --- | --- |")
        for it in rows:
            val = it["value"] + ((" " + it["unit"]) if it["unit"] else "")
            src = it["source_url"]
            src_cell = "[%s](%s)" % (PAGES.get(src, src), src) if src else ""
            mid = ("`%s`" % it["model_id"]) if it["model_id"] else ""
            out.append("| `%s` | %s | %s | %s | %s | %s |" % (
                it["key"], cell(val), cell(mid), cell(it["verified"]), src_cell, cell(it["note"])))
        out.append("")
    out.append(END)
    return "\n".join(out)


def locate(text):
    lines = text.split("\n")
    s = [i for i, l in enumerate(lines) if l == START]
    e = [i for i, l in enumerate(lines) if l == END]
    if text.count("<!-- figures:start") != 1 or text.count("<!-- figures:end") != 1:
        raise InputError("markers must each appear exactly once (start %d, end %d)"
                         % (text.count("<!-- figures:start"), text.count("<!-- figures:end")))
    if len(s) != 1 or len(e) != 1:
        raise InputError("markers must each sit alone on their own line, with the exact start text")
    if s[0] >= e[0]:
        raise InputError("start marker must precede end marker")
    return lines, s[0], e[0]


def main(argv):
    check = False
    args = argv[1:]
    if args and args[0] == "--check":
        check, args = True, args[1:]
    if len(args) != 2:
        sys.stderr.write(__doc__)
        return 2
    yaml_path, target = args
    try:
        items = parse(yaml_path)
        with open(target, encoding="utf-8") as fh:
            text = fh.read()
        lines, si, ei = locate(text)
    except (InputError, OSError) as exc:
        sys.stderr.write("build_appendix_i: %s\n" % exc)
        return 2
    block = render(items)
    current = "\n".join(lines[si:ei + 1])
    if check:
        if current != block:
            sys.stderr.write("build_appendix_i: generated block in %s is stale\n" % target)
            return 1
        print("build_appendix_i: %s up to date (%d figures)" % (target, len(items)))
        return 0
    new = "\n".join(lines[:si] + block.split("\n") + lines[ei + 1:])
    if new != text:
        with open(target, "w", encoding="utf-8") as fh:
            fh.write(new)
        print("build_appendix_i: wrote %d figures into %s" % (len(items), target))
    else:
        print("build_appendix_i: %s already current (%d figures)" % (target, len(items)))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
